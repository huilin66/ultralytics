"""Per-sequence-group evaluation of the R-LiViT E2 baselines for the F1 falsification analysis.

Scores every test sequence group (12 images each) separately for B0/B1/B3/B4/B5/B7, so the paired
per-group deltas B3-B0, B4-B0, B5-B1 and B7-B3 show whether fusion gains are uniform or come from a
few sequences. Group data yamls are generated by this script into ``--work`` (one per group and
condition, because each condition needs its own channel count and ``modalities`` list).

Usage:
    python tools/eval_f1_groups.py --runs runs/e2_rlivit --out runs/e2_rlivit/f1_group_eval.json
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from ultralytics import YOLO  # noqa: E402
from ultralytics.models.multimodal import MultiModalYOLO  # noqa: E402

# tag -> (weights relative to --runs, companion modalities, primary modality)
MODELS = {
    "B0": ("b0-rgb-seed0/weights/best.pt", [], "rgb"),
    "B1": ("b1-thermal-seed0/weights/best.pt", [], "thermal"),
    "B3": ("b3-rgb-t-seed0/weights/best.pt", ["thermal"], "rgb"),
    "B4": ("b4-rgb-d-seed0/weights/best.pt", ["depth"], "rgb"),
    "B5": ("b5-t-d-seed0/weights/best.pt", ["depth"], "thermal"),
    "B7": ("../e15_rlivit_b4_200ep/yolo26x-mm3-bf-seed0/weights/best.pt", ["thermal", "depth"], "rgb"),
}
MODALITY_CH = {"rgb": (3, "bgr"), "thermal": (1, None), "depth": (1, None)}


def build_group_files(data_root: Path, work: Path, split: str = "test") -> dict[str, list[str]]:
    """Write one image-list txt per group and modality, plus one data yaml per group and condition."""
    manifest = Path(data_root) / "metadata" / "split_manifest.csv"
    groups = defaultdict(list)
    with open(manifest, newline="") as f:
        for row in csv.DictReader(f):
            if row["split"] == split:
                groups[row["group"]].append(row["sample_id"])
    classes = json.loads((Path(data_root) / "metadata" / "classes.json").read_text())["names"]
    names = {idx: name for name, idx in classes.items()}

    work.mkdir(parents=True, exist_ok=True)
    for gid, ids in sorted(groups.items()):
        for mod in ("rgb", "thermal", "depth"):
            paths = sorted(str(Path(data_root) / "images" / mod / split / f"{i}.png") for i in ids)
            (work / f"g{gid}_{mod}.txt").write_text("\n".join(paths) + "\n")
    for tag, (_, mods, primary) in MODELS.items():
        mlist = [{"name": primary, "path": f"images/{primary}", "channels": MODALITY_CH[primary][0], "suffix": ".png"}]
        if MODALITY_CH[primary][1]:
            mlist[0]["color"] = MODALITY_CH[primary][1]
        for m in mods:
            mlist.append({"name": m, "path": f"images/{m}", "channels": MODALITY_CH[m][0], "suffix": ".png"})
        for gid in groups:
            txt = str(work / f"g{gid}_{primary}.txt")
            cfg = {
                "path": str(data_root),
                "train": txt,
                "val": txt,
                "test": txt,
                "channels": sum(m["channels"] for m in mlist),
                "names": names,
            }
            if tag != "B0":  # single-branch RGB needs no modality companions
                cfg["modalities"] = mlist
            (work / f"data_{tag}_g{gid}.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    return dict(sorted(groups.items()))


def restore_fusion_defaults(model) -> None:
    """Give pre-e406b4a26 ``MultiModalFusion`` modules their missing ``projections``/``residuals``/``gates``.

    The E1.5 checkpoints (B7 = A3 BF) were pickled before those submodules existed and ``forward`` reads them
    unconditionally. For the ``concat`` operator the correct value is ``None``.
    """
    from ultralytics.models.multimodal.modules import MultiModalFusion

    for m in model.modules():
        if isinstance(m, MultiModalFusion):
            for attr in ("projections", "residuals", "gates"):
                if attr not in m.__dict__:
                    object.__setattr__(m, attr, None)


def main(opt) -> None:
    runs = Path(opt.runs)
    out = Path(opt.out)
    groups = build_group_files(Path(opt.data_root), Path(opt.work), opt.split)
    rows, done = [], set()
    if out.exists():
        rows = json.loads(out.read_text())
        done = {(r["group"], r["model"]) for r in rows}

    for tag, (weights, _, _) in MODELS.items():
        pending = [g for g in groups if (g, tag) not in done]
        if not pending:
            continue
        model_cls = YOLO if tag == "B0" else MultiModalYOLO
        model = model_cls(str(runs / weights), task="detect")
        restore_fusion_defaults(model.model)
        for gid in pending:
            r = model.val(
                data=str(Path(opt.work) / f"data_{tag}_g{gid}.yaml"),
                split=opt.split,
                imgsz=opt.imgsz,
                batch=opt.batch,
                device=opt.device,
                plots=False,
                save_json=False,
                verbose=False,
            )
            per_class = r.box.maps.tolist() if getattr(r.box, "maps", None) is not None else []
            row = {
                "group": gid,
                "model": tag,
                "map": float(r.box.map),
                "map50": float(r.box.map50),
                "per_class": per_class,
            }
            rows.append(row)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(json.dumps(rows, indent=1))
            print(f"{tag} {gid}: mAP50-95 {row['map']:.4f}", flush=True)
        del model
    print(f"rows: {len(rows)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs/e2_rlivit")
    ap.add_argument("--data-root", default="/srv/nas/home/dataset/R-LiViT_mdet")
    ap.add_argument("--work", default="/tmp/f1_groups")
    ap.add_argument("--out", default="runs/e2_rlivit/f1_group_eval.json")
    ap.add_argument("--split", default="test")
    ap.add_argument("--imgsz", type=int, default=640)
    ap.add_argument("--batch", type=int, default=4)
    ap.add_argument("--device", default="0")
    opt = ap.parse_args()
    os.environ.setdefault("YOLO_VERBOSE", "false")
    main(opt)
