"""Canonical schema shared by every raw-dataset adapter.

The converted layout is dictated by ``ultralytics.data.multimodal`` and
``ultralytics.data.utils.img2label_paths``:

* the primary modality lives under ``images/<primary>/<split>/``;
* every other modality mirrors the same relative sub-path under its own root;
* labels must sit at ``labels/<primary>/<split>/`` because ``img2label_paths``
  swaps the ``images`` path segment for ``labels`` and keeps the rest.

Nothing in this module imports ``ultralytics`` so the converters stay runnable
in a bare environment.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

# Modality names are fixed by the research plan: MID-3K "intensity" is not "thermal".
MODALITY_NAMES = ("rgb", "thermal", "depth")

SPLITS = ("train", "val", "test")


@dataclass(frozen=True)
class EncodeSpec:
    """Declarative raw -> uint8 mapping, recorded verbatim in the metadata.

    ``ultralytics`` multi-modal loading requires every modality to be ``uint8``
    (see ``Modalities.load``).  Non-8-bit sensors therefore have to be mapped
    here, explicitly and reproducibly, instead of being rescaled silently by the
    dataloader.

    Attributes:
        kind: ``rgb`` keeps a three-channel BGR image, ``gray`` reduces to one
            channel, ``scaled`` applies the ``lo``/``hi`` affine map.
        units: Physical unit of the stored values (``"mm"``, ``"m"``, ``"K"``,
            ``"raw"`` ...).  Informational only, never used for math.
        lo: Raw value mapped to 0.
        hi: Raw value mapped to 255.
        invalid: Raw values that mean "no measurement"; they are mapped to 0 and
            counted as invalid pixels.
        note: Human-readable justification stored next to the conversion params.
    """

    kind: str
    units: str = "raw"
    lo: float = 0.0
    hi: float = 255.0
    invalid: tuple[float, ...] = ()
    note: str = ""

    def describe(self) -> dict:
        """Return a JSON-serialisable description for the conversion manifest."""
        return {
            "kind": self.kind,
            "units": self.units,
            "lo": self.lo,
            "hi": self.hi,
            "invalid": list(self.invalid),
            "note": self.note,
            "formula": None if self.kind != "scaled" else "(clip(x, lo, hi) - lo) / (hi - lo) * 255",
        }


@dataclass(frozen=True)
class ModalitySpec:
    """One declared modality of the converted dataset."""

    name: str
    channels: int
    encode: EncodeSpec
    color: str | None = None
    suffix: str = ".png"
    required: bool = True

    def yaml_entry(self) -> dict:
        """Return the ``modalities`` entry consumed by the multi-modal loader."""
        entry = {"name": self.name, "path": f"images/{self.name}", "channels": self.channels, "suffix": self.suffix}
        if self.color:
            entry["color"] = self.color
        return entry


@dataclass
class Box:
    """One detection box in reference-image pixel coordinates."""

    class_name: str
    xyxy: tuple[float, float, float, float]
    source: str = "official_box"
    ignored: bool = False
    note: str = ""


@dataclass
class RawSample:
    """A single multi-modal sample discovered in the raw tree."""

    sample_id: str
    group: str
    files: dict[str, Path] = field(default_factory=dict)
    boxes: list[Box] = field(default_factory=list)
    split: str | None = None
    annotation_status: str = "official_box"
    note: str = ""


@dataclass
class DatasetPlan:
    """Everything an adapter declares before a byte is written."""

    key: str
    display_name: str
    reference_modality: str
    modalities: tuple[ModalitySpec, ...]
    classes: dict[str, int]
    samples: list[RawSample]
    splits: dict[str, str] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    source: dict = field(default_factory=dict)

    @property
    def channels(self) -> int:
        """Total channel count of the fused input tensor."""
        return sum(m.channels for m in self.modalities)

    @property
    def reference(self) -> ModalitySpec:
        """Return the modality that defines the label coordinate frame."""
        return next(m for m in self.modalities if m.name == self.reference_modality)


def format_yaml(plan: DatasetPlan, root: Path) -> str:
    """Render the ``data.yaml`` consumed by ``yolo train data=...``."""
    lines = [
        "# Ultralytics 🚀 AGPL-3.0 License - https://ultralytics.com/license",
        f"# Generated by tools/convert_dataset.py from {plan.display_name}.",
        f"# Reference (label) frame: {plan.reference_modality}. Labels live under labels/{plan.reference_modality}/.",
        "",
        f"path: {root.as_posix()}",
    ]
    for split in SPLITS:
        if split in plan.splits:
            lines.append(f"{split}: images/{plan.reference_modality}/{split}")
        else:
            lines.append(f"{split}:")
    lines.append("")
    lines.append(f"channels: {plan.channels}")
    lines.append("")
    lines.append("names:")
    for name, index in sorted(plan.classes.items(), key=lambda kv: kv[1]):
        lines.append(f"  {index}: {name}")
    lines.append("")
    lines.append("modalities:")
    for modality in plan.modalities:
        entry = modality.yaml_entry()
        body = ", ".join(f"{k}: {v}" for k, v in entry.items())
        lines.append(f"  - {{{body}}}")
    lines.append("")
    return "\n".join(lines)
